#!/usr/bin/env ruby
# frozen_string_literal: true

# The standard-voice pipeline (rulebook §2, owner ruling 2026-08-15):
# ALL course audio — syllable citations and classical reading lines —
# is synthesized in ONE pinned voice (ElevenLabs), replacing the
# uneven human-clip patchwork. Modus operandi (owner-designed):
#
#   batch      — agent-run: read the plan (voice-plan.yml) and the
#                ledger of already-built clips (voice-ledger.yml),
#                write the pending work to voice-batch.json.
#   synth      — HUMAN-run, never the agent (golden rule 3: network-
#                mutating; golden rule 8: the key never enters the
#                repo). Reads env: ELEVENLABS_API_KEY (required),
#                ELEVENLABS_VOICE_ID, ELEVENLABS_MODEL_ID,
#                ELEVENLABS_OUTPUT_FORMAT (env overrides plan).
#                Synthesizes each batch item into staging/.
#   integrate  — agent-run: QA every staged clip (trim silence;
#                syllables pitch-verified against the declared tone
#                and span-checked, exactly as the old pipeline
#                demanded of human clips; lines duration-checked
#                with a syllable-count report), loudness-normalize
#                to −20 dB mean / −1 dB peak, encode mono 64k mp3
#                into the site, record in the ledger, regenerate
#                credits. A clip that fails QA does not ship; the
#                next batch re-requests it.
#   voices     — HUMAN-run helper: list the account's voices.
#
# Requires ffmpeg. Network only in the two HUMAN subcommands.
#
# Usage: ruby bin/pinyin_voice.rb batch [--all]
#        ruby bin/pinyin_voice.rb synth
#        ruby bin/pinyin_voice.rb integrate [--force id ...]
#        ruby bin/pinyin_voice.rb voices

require "yaml"
require "json"
require "net/http"
require "uri"
require "fileutils"
require_relative "pinyin_audio"

PLAN    = "assets-src/data/voice-plan.yml"
LEDGER  = "assets-src/data/voice-ledger.yml"
BATCH   = "assets-src/audio/voice-batch.json"
STAGING = "assets-src/audio/staging"
OUT_SYL = "site/assets/audio/pinyin"
OUT_LIN = "site/assets/audio/lines"
API_BASE = "https://api.elevenlabs.io"

module Edubba
  module PinyinVoice
    module_function

    # Engine config: the plan carries the pinned defaults; env
    # overrides each field (the owner's working contract). The API
    # key is env-only, by law.
    def resolve_engine(plan_engine, env)
      e = (plan_engine || {}).dup
      e["voice_id"] = env["ELEVENLABS_VOICE_ID"] if env["ELEVENLABS_VOICE_ID"].to_s != ""
      e["model_id"] = env["ELEVENLABS_MODEL_ID"] if env["ELEVENLABS_MODEL_ID"].to_s != ""
      e["output_format"] = env["ELEVENLABS_OUTPUT_FORMAT"] if env["ELEVENLABS_OUTPUT_FORMAT"].to_s != ""
      e["model_id"] ||= "eleven_multilingual_v2"
      e["output_format"] ||= "mp3_44100_128"
      e
    end

    def out_path(id, kind)
      kind == "line" ? File.join(OUT_LIN, "#{id}.mp3") : File.join(OUT_SYL, "#{id}.mp3")
    end

    # Credits regeneration — every path that ships a clip (integrate,
    # approve) must leave the credits files matching the ledger.
    # Ear-approved takes ledger a "(per take)" model placeholder (the
    # winning take's model is not recoverable across archived runs);
    # the engine line names only real model ids.
    def write_credits(ledger)
      models = ledger["built"].values.map { |b| b["model_id"] }
                     .compact.uniq.reject { |m| m.start_with?("(") }
      eng_line = "ElevenLabs #{models.join('/')}" \
                 " · voice #{ledger['built'].values.map { |b| b['voice_id'] }.compact.uniq.join('/')}"
      syl = ledger["built"].select { |id, _| File.exist?(File.join(OUT_SYL, "#{id}.mp3")) }
      lin = ledger["built"].select { |id, _| File.exist?(File.join(OUT_LIN, "#{id}.mp3")) }
      # Attribution law: any clip NOT yet regenerated is still a
      # Commons recording and keeps its CC attribution line —
      # carried forward from the previous credits file until the
      # standard voice replaces it.
      credits_f = File.join(OUT_SYL, "CREDITS-syllables.txt")
      legacy = File.exist?(credits_f) ?
                 File.read(credits_f).lines
                     .select { |l| l =~ /\A(\S+)\.mp3\s+— / && !ledger["built"].key?(Regexp.last_match(1)) } : []
      legacy_block = legacy.empty? ? "" :
        "\nLegacy clips (Wikimedia Commons era), pending regeneration:\n#{legacy.join}"
      File.write(credits_f, <<~TXT + legacy_block)
        Per-syllable audio credits
        ==========================
        GENERATED by bin/pinyin_voice.rb — do not edit by hand.
        The clips listed below are SYNTHESIZED in one standard voice
        (#{eng_line}), then pitch-verified against the declared tone
        and loudness-normalized (mono 64 kbps mp3). The rulebook
        (docs/courses/sinographs.md §2) records the ruling: no native
        speakers of the classical language exist; one consistent
        conventional voice teaches best.
        #{syl.keys.sort.map { |id| "#{id}.mp3" }.join("\n")}
      TXT
      return if lin.empty?

      FileUtils.mkdir_p(OUT_LIN)
      File.write(File.join(OUT_LIN, "CREDITS-lines.txt"), <<~TXT)
        Reading-line audio credits
        ==========================
        GENERATED by bin/pinyin_voice.rb — do not edit by hand.
        All line audio is SYNTHESIZED in the same standard voice as
        the syllable citations (#{eng_line}); modern Mandarin
        readings of classical text, duration-checked and
        loudness-normalized.
        #{lin.keys.sort.map { |id| "#{id}.mp3" }.join("\n")}
      TXT
    end

    # Pending work: every plan item not yet in the ledger (or all of
    # them with all: true — the wholesale regeneration mode).
    #
    # Variant fan-out (owner design 2026-08-15: "make MANY versions
    # with the same syllables, and check what works"): a syllable may
    # carry `variants:` — a list of {text, cut, voice_settings}
    # strategies — and rolls > 1 duplicates every strategy for
    # stochastic retries. Each attempt becomes its own batch item
    # (id~v0a, id~v0b, id~v1a …) sharing the base id and out path;
    # integrate ships the first attempt that passes QA.
    def pending_items(plan, ledger, all: false, rolls: 1)
      built = ledger.fetch("built", {})
      items = []
      (plan["syllables"] || {}).each do |id, s|
        next if !all && built.key?(id)

        specs = s["variants"] || [s]
        specs.each_with_index do |spec, vi|
          rolls.times do |roll|
            item = { "id" => specs.length * rolls == 1 ? id : "#{id}~v#{vi}#{('a'.ord + roll).chr}",
                     "base" => id, "kind" => s["kind"] || "syllable",
                     "text" => spec["text"], "pinyin" => s["pinyin"],
                     "verify" => s["verify"] || "tone",
                     "out" => out_path(id, "syllable") }
            item["cut"] = spec["cut"] if spec["cut"]
            item["stretch"] = spec["stretch"] if spec["stretch"]
            # Syllable items default to the engine's deliberate
            # citation pace (syllable_voice_settings) and teacher-
            # register prosody context (syllable_previous_text —
            # conditions HOW the text is spoken without being
            # spoken itself; the cooperative hint, owner question
            # 2026-08-15). A spec's own fields win. Lines keep
            # natural prosody.
            settings = spec["voice_settings"] ||
                       (s["verify"] != "loudness" && plan.dig("engine", "syllable_voice_settings")) || nil
            item["voice_settings"] = settings if settings
            prev = spec["previous_text"] ||
                   (s["verify"] != "loudness" && plan.dig("engine", "syllable_previous_text")) || nil
            if prev
              # rotate the priming text per roll — a cache-buster
              # that survives seed rejection (2026-08-15: er~v0a/b/c
              # byte-identical; identical requests return identical
              # audio, and `seed` was dropped by the 400 dance)
              item["previous_text"] = [prev, "請#{prev}", "現在，#{prev}"][roll % 3]
            end
            item["next_text"] = spec["next_text"] if spec["next_text"]
            items << item
          end
        end
      end
      (plan["lines"] || {}).each do |id, l|
        next if !all && built.key?(id)

        items << { "id" => id, "base" => id, "kind" => "line",
                   "text" => l["text"], "pinyin" => l["pinyin"],
                   "verify" => l["verify"] || "line",
                   "out" => out_path(id, "line") }
      end
      items
    end

    # Track hygiene for synthesized cuts (2026-08-15): the
    # autocorrelation tracker, tuned on clean dedicated recordings,
    # throws octave-jump garbage on TTS fricative onsets (學 tracked
    # 85↔356 Hz frame to frame — physically impossible). Median-3
    # filter, then clip to a physiological band around the track's
    # median (0.6×–1.6×) and drop what falls outside. The contour
    # LAW is untouched — only the measurement is cleaned.
    def clean_track(track)
      return track if track.length < 3

      med3 = track.each_index.map do |i|
        a = [i - 1, 0].max
        b = [i + 1, track.length - 1].min
        track[a..b].sort[(b - a) / 2]
      end
      center = med3.sort[med3.length / 2].to_f
      med3.select { |f| f.between?(center * 0.6, center * 1.6) }
    end

    # Late-rise detector (2026-08-15, the cháng blind spot): a slow
    # deliberate tone-2 may hold a long low dip and rise steeply
    # only in the final fifth — which the feature windows trim and
    # median away (chang~v2c: 126→113 dip, then 113→155, refused).
    # Accept a rise when the track's tail clearly climbs ≥22% out
    # of the mid-track valley and keeps climbing. Falls end low and
    # levels never leave the valley — both still refuse.
    def late_rise?(track)
      return false if track.length < 8

      tail = track.last([track.length / 4, 3].max)
      mid = track[(track.length / 5)...(track.length * 4 / 5)]
      valley = mid.min.to_f
      tail.max > valley * 1.22 && tail.last >= tail.first
    end

    # THE TRANSCRIPT GATE (owner catches, 2026-08-15: mā shipped as
    # "mama", mù as "musha", dà as "dar" — acoustic QA verified the
    # pitch and length OF GARBAGE). Every clip must be RECOGNIZED
    # as saying what it claims before it ships: whisper.cpp,
    # forced-zh decode, offline. A syllable transcript must be
    # exactly one han character from the accepted set (the carrier
    # and same-sound characters of our own pool); anything Latin,
    # empty, or multi-character is babble and refuses. Never ship
    # speech the pipeline has not understood.
    WHISPER_MODEL = ENV.fetch("EDUBBA_WHISPER_MODEL",
                              File.expand_path("~/.cache/edubba-whisper/ggml-small.bin"))

    def transcribe(wav)
      # beam search + a neutral domain prompt (NOT the expected
      # answer — that would teach the recognizer to hallucinate the
      # expectation) markedly improves isolated-syllable decoding
      out = `whisper-cli -m #{WHISPER_MODEL.inspect} -l zh -nt -bs 5 --prompt "以下是普通話單字的清晰發音。" -f #{wav.inspect} 2>/dev/null`
      out.force_encoding(Encoding::UTF_8).scrub("") # babble can break bytes, not just sense
         .gsub(/\s+/, "").gsub(/[。，、？！?!,.:：;；'"「」…-]/, "")
         .sub("以下是普通話單字的清晰發音", "") # prompt echo, when audio is near-empty
    end

    def han_only(str)
      str.scan(/\p{Han}/).join
    end

    # Segmental identity via Unihan kMandarin (Nabu's canonical
    # copy): the transcript character must SAY the expected base
    # syllable — any tone (the pitch gate owns tones), any script
    # (simplified 时 reads shí too). 約 clears yuē, 蛋 clears dàn;
    # 是-for-zì and Latin babble refuse.
    UNIHAN_READINGS = File.join(
      ENV.fetch("UNIHAN_DIR", File.expand_path("~/Dev/nabu/canonical/unihan")),
      "Unihan_Readings.txt"
    )

    def unihan_pinyin
      @unihan_pinyin ||= begin
        map = Hash.new { |h, k| h[k] = [] }
        File.foreach(UNIHAN_READINGS) do |line|
          # kMandarin gives the customary reading only — 長 lists
          # zhǎng and loses cháng. kHanyuPinyin carries the full
          # reading set (10063.130:cháng,zhǎng); union both.
          if line.include?("\tkMandarin\t")
            cp, _, vals = line.strip.split("\t", 3)
            ch = [cp.sub("U+", "").hex].pack("U")
            map[ch] |= vals.split(/\s+/)
          elsif line.include?("\tkHanyuPinyin\t")
            cp, _, vals = line.strip.split("\t", 3)
            ch = [cp.sub("U+", "").hex].pack("U")
            map[ch] |= vals.split(/\s+/).flat_map { |v| v.sub(/\A[\d.,*]+:/, "").split(",") }
          end
        end
        map
      end
    end

    def base_syllable(pinyin)
      pinyin.to_s.unicode_normalize(:nfd).gsub(/\p{Mn}/, "").downcase
    end

    def lcs_length(a, b)
      dp = Array.new(b.length + 1, 0)
      a.each do |x|
        prev = 0
        b.each_with_index do |y, j|
          cur = dp[j + 1]
          dp[j + 1] = x == y ? prev + 1 : [dp[j + 1], dp[j]].max
          prev = cur
        end
      end
      dp[b.length]
    end

    # ASR writes numbers as digits (三十而立 → "32里") — expand a
    # digit run to its spoken Chinese bases before comparison.
    DIGIT_BASE = %w[ling yi er san si wu liu qi ba jiu].freeze

    def expand_digits(str)
      out = []
      str.scan(/\d+|\p{Han}/) do |tok|
        if tok =~ /\A\d+\z/
          n = tok.to_i
          if n.between?(10, 99)
            out << DIGIT_BASE[n / 10] unless n / 10 == 1
            out << "shi"
            out << DIGIT_BASE[n % 10] unless (n % 10).zero?
          else
            tok.each_char { |d| out << DIGIT_BASE[d.to_i] }
          end
        else
          out << tok
        end
      end
      out
    end

    # -n/-ng codas are the most confused pair in Mandarin ASR
    # (chen→cheng); folded for LINE comparison only — syllable
    # clips still face the strict segmental test.
    def fold_coda(base)
      base.sub(/ng\z/, "n")
    end

    def says_base?(char, expected_pinyin)
      want = base_syllable(expected_pinyin)
      unihan_pinyin.fetch(char, []).any? { |p| base_syllable(p) == want }
    end

    # Syllable count a line's pinyin declares (for the hump report).
    def syllable_count(pinyin)
      pinyin.to_s.split(/[\s,，。？！?!:：]+/).reject(&:empty?).size
    end

    # The middle token of a triple-carrier utterance (X、X、X。),
    # located on the ENERGY ENVELOPE (25 ms frames, PinyinAudio's) —
    # silence detection failed on connected list readings
    # (2026-08-15: "0 silences" on 大、大、大。 spoken without gaps),
    # but even connected repetitions dip between syllables. Returns
    # [from_s, to_s] or nil.
    #
    # Separated tokens: pick the voiced run nearest the center.
    # Connected (one run): split at the lowest internal valleys in
    # the run's middle thirds; the slice between them is the middle
    # token. A middle shorter than 75 ms is a failed split.
    FRAME_S = Edubba::PinyinAudio::FRAME / 16_000.0

    def middle_token(env)
      token_at(env, :middle)
    end

    # position :middle — the center token of a triple (X、X、X。);
    # :first — the opening syllable of a disyllabic carrier word
    # (時間 for shí): first position in a word gets full careful
    # articulation where isolated repetition sags (2026-08-15, the
    # eleven stragglers — eight of them tone-2 rises).
    def token_at(env, position)
      peak = env.max.to_f
      return nil if peak <= 0

      mask = env.map { |e| e >= peak * Edubba::PinyinAudio::HUMP_FLOOR }
      runs = []
      mask.each_with_index do |v, i|
        if v && runs.last && runs.last.last == i - 1 then runs.last[1] = i
        elsif v then runs << [i, i]
        end
      end
      # join runs split by 1-frame dips (the humps law's tolerance)
      runs = runs.each_with_object([]) do |r, acc|
        if acc.last && r[0] - acc.last[1] <= 2 then acc.last[1] = r[1]
        else acc << r
        end
      end
      return nil if runs.empty?

      if runs.length >= 2
        pick = if position == :first then runs.first
               elsif position == :second then runs[1]
               elsif position.to_s =~ /\Atoken(\d+)\z/
                 # tokenN (1-based) demands the tokens separated —
                 # cutting the four-tone bar into its four demos
                 n = Regexp.last_match(1).to_i
                 runs.length >= n ? runs[n - 1] : nil
               else runs.min_by { |a, b| ((a + b) / 2.0 - env.length / 2.0).abs }
               end
        return pick && [pick[0] * FRAME_S, (pick[1] + 1) * FRAME_S]
      end
      # :second demands separated tokens — a connected four-tone
      # paradigm can't be split reliably; refuse and re-roll.
      return nil if position == :second

      a, b = runs.first
      len = b - a + 1
      if position == :first
        return nil if len < 6 # under ~150 ms can't hold two tokens

        v1 = (a + len / 4..a + 3 * len / 4).min_by { |i| env[i] }
        return nil if v1 - a < 3

        return [a * FRAME_S, v1 * FRAME_S]
      end
      return nil if len < 9 # under ~225 ms can't hold three tokens

      v1 = (a + len / 6..a + len / 2).min_by { |i| env[i] }
      v2 = (a + len / 2..a + 5 * len / 6).min_by { |i| env[i] }
      return nil if v2 - v1 < 3

      [(v1 + 1) * FRAME_S, v2 * FRAME_S]
    end
  end
end

if $PROGRAM_NAME == __FILE__
  cmd = ARGV.shift or abort "usage: pinyin_voice.rb batch|synth|integrate|voices"
  plan = YAML.safe_load_file(PLAN)
  ledger = File.exist?(LEDGER) ? YAML.safe_load_file(LEDGER) : { "built" => {} }
  engine = Edubba::PinyinVoice.resolve_engine(plan["engine"], ENV)

  case cmd
  when "batch"
    rolls = ARGV.include?("--rolls") ? ARGV[ARGV.index("--rolls") + 1].to_i : 1
    items = Edubba::PinyinVoice.pending_items(plan, ledger, all: ARGV.include?("--all"),
                                                            rolls: [rolls, 1].max)
    if items.empty?
      puts "voice batch: nothing pending — plan fully built (use --all to regenerate)"
      exit 0
    end
    FileUtils.mkdir_p(File.dirname(BATCH))
    File.write(BATCH, JSON.pretty_generate(
                        "engine" => engine.reject { |k, _| k == "api_key" },
                        "items" => items
                      ))
    puts "voice batch: #{items.size} item(s) -> #{BATCH}"
    puts "  syllables: #{items.count { |i| i['kind'] != 'line' }}, lines: #{items.count { |i| i['kind'] == 'line' }}"
    puts "Owner: run  ELEVENLABS_API_KEY=... [ELEVENLABS_VOICE_ID=...] rake voice:synth"

  when "synth"
    key = ENV["ELEVENLABS_API_KEY"].to_s
    abort "voice synth: ELEVENLABS_API_KEY not set — this is the owner-run step" if key.empty?
    abort "voice synth: no batch file (run rake voice:batch first)" unless File.exist?(BATCH)
    batch = JSON.parse(File.read(BATCH))
    eng = batch["engine"].merge(Edubba::PinyinVoice.resolve_engine(batch["engine"], ENV))
    abort "voice synth: no voice id — set ELEVENLABS_VOICE_ID or engine.voice_id in #{PLAN}" if eng["voice_id"].to_s.empty?
    FileUtils.mkdir_p(STAGING)
    done = 0
    skipped = 0
    failures = []
    rejected_params = [] # discovered once, applied to the whole run
    batch["items"].each do |item|
      staged = File.join(STAGING, "#{item['id']}.mp3")
      if File.exist?(staged)
        skipped += 1
        next
      end
      uri = URI("#{API_BASE}/v1/text-to-speech/#{eng['voice_id']}?output_format=#{eng['output_format']}")
      # v3 models take bracketed audio tags as delivery directives
      # ([slowly] — deliberate pace without the speed slider's
      # prosody flattening); applied to syllable items only, and
      # only when a v3 model actually runs.
      text = item["text"]
      if eng["model_id"].to_s.start_with?("eleven_v3") && eng["v3_text_prefix"] && item["kind"] != "line"
        text = "#{eng['v3_text_prefix']}#{text}"
      end
      body = { "text" => text, "model_id" => eng["model_id"] }
      body["language_code"] = eng["language"] if eng["language"].to_s != ""
      settings = item["voice_settings"] || eng["voice_settings"]
      body["voice_settings"] = settings if settings
      body["previous_text"] = item["previous_text"] if item["previous_text"]
      body["next_text"] = item["next_text"] if item["next_text"]
      # identical requests can return byte-identical audio (v3 is
      # cache-deterministic — ren~v0a == ren~v0b, 2026-08-15); a
      # random seed makes every roll an actual roll
      body["seed"] = rand(2**31)
      body.delete_if { |k, _| rejected_params.include?(k) }
      req = Net::HTTP::Post.new(uri, "xi-api-key" => key, "Content-Type" => "application/json")
      req.body = JSON.generate(body)
      res = Net::HTTP.start(uri.hostname, uri.port, use_ssl: true, read_timeout: 120) { |h| h.request(req) }
      # Smart 400 handling: the API names the offending field —
      # drop ONLY that one, remember it for the whole run, keep
      # every other hint alive. (The blunt strip-everything retry
      # silently removed language enforcement from every v3 request
      # — the 2026-08-15 babble.)
      tries = 0
      while res.code == "400" && tries < 4
        offender = (body.keys - %w[text model_id]).find { |k| res.body.include?(k) }
        break unless offender

        rejected_params << offender
        puts "  model rejects #{offender} — dropped for this run" if rejected_params.size != (@warned ||= []).size && @warned << offender
        body.delete(offender)
        req.body = JSON.generate(body)
        res = Net::HTTP.start(uri.hostname, uri.port, use_ssl: true, read_timeout: 120) { |h| h.request(req) }
        tries += 1
      end
      if res.code == "400"
        req.body = JSON.generate({ "text" => body["text"], "model_id" => body["model_id"] })
        res = Net::HTTP.start(uri.hostname, uri.port, use_ssl: true, read_timeout: 120) { |h| h.request(req) }
      end
      if res.code == "200"
        File.binwrite(staged, res.body)
        done += 1
        puts "synth #{item['id']} (#{res.body.bytesize} bytes)"
      else
        failures << "#{item['id']}: HTTP #{res.code} #{res.body[0, 200]}"
      end
      sleep 0.4
    end
    # Record which voice actually spoke (sans key) so integrate can
    # ledger true provenance — env at synth time is the authority.
    File.write(File.join(STAGING, "_engine.json"),
               JSON.pretty_generate(eng.reject { |k, _| k == "api_key" }))
    puts "voice synth: #{done} synthesized, #{skipped} already staged, #{failures.size} failed"
    failures.each { |f| puts "  FAIL #{f}" }
    puts "Next: rake voice:integrate (agent-run QA + site encode)" if failures.empty?
    exit(failures.empty? ? 0 : 1)

  when "integrate"
    abort "voice integrate: ffmpeg not found" if `which ffmpeg`.empty?
    abort "voice integrate: whisper-cli not found — the transcript gate is law" if `which whisper-cli`.empty?
    abort "voice integrate: whisper model missing at #{Edubba::PinyinVoice::WHISPER_MODEL}" \
      unless File.exist?(Edubba::PinyinVoice::WHISPER_MODEL)
    abort "voice integrate: no batch file" unless File.exist?(BATCH)
    batch = JSON.parse(File.read(BATCH))
    engine_used = File.exist?(File.join(STAGING, "_engine.json")) ?
                    JSON.parse(File.read(File.join(STAGING, "_engine.json"))) : batch["engine"]
    force = ARGV.reject { |a| a.start_with?("--") }
    built = 0
    failures = []
    tmp = File.join(STAGING, "_work")
    rejected = File.join(STAGING, "rejected")
    FileUtils.mkdir_p(tmp)
    FileUtils.mkdir_p(rejected)
    # QA one staged attempt: returns the trimmed/cut wav path on
    # pass, or a refusal reason string.
    qa = lambda do |item, staged|
      id = item["id"]
      trimmed = File.join(tmp, "#{id}.wav")
      system("ffmpeg", "-v", "quiet", "-y", "-i", staged,
             "-af", "silenceremove=start_periods=1:start_threshold=-40dB:start_silence=0.05," \
                    "areverse,silenceremove=start_periods=1:start_threshold=-30dB:start_silence=0.05,areverse",
             trimmed)
      return [nil, "trim produced nothing usable"] unless File.exist?(trimmed) && File.size(trimmed) > 1000

      if item["cut"].to_s.match?(/\A(middle|first|second|token\d+)\z/)
        pre_pcm = File.join(tmp, "#{id}-pre.pcm")
        system("ffmpeg", "-v", "quiet", "-y", "-i", trimmed, "-f", "s16le", "-ac", "1", "-ar", "16000", pre_pcm)
        seg = Edubba::PinyinVoice.token_at(Edubba::PinyinAudio.envelope(File.binread(pre_pcm)),
                                           item["cut"].to_sym)
        return [nil, "carrier token (#{item['cut']}) not separable on the envelope"] if seg.nil?

        cutf = File.join(tmp, "#{id}-cut.wav")
        system("ffmpeg", "-v", "quiet", "-y", "-i", trimmed,
               "-ss", format("%.3f", [seg[0] - 0.02, 0].max), "-to", format("%.3f", seg[1] + 0.02), cutf)
        trimmed = cutf
      end
      if item["stretch"]
        # Pitch-preserving time-stretch (the language-lab slowdown):
        # for inherently clipped syllables (checked-tone history —
        # 踏 never reaches the length floor at any prompt). The tone
        # and span gates run on the STRETCHED result.
        sf = File.join(tmp, "#{id}-slow.wav")
        system("ffmpeg", "-v", "quiet", "-y", "-i", trimmed,
               "-af", format("atempo=%.3f", 1.0 / item["stretch"].to_f), sf)
        trimmed = sf if File.exist?(sf) && File.size(sf) > 1000
      end
      pcm_f = File.join(tmp, "#{id}.pcm")
      system("ffmpeg", "-v", "quiet", "-y", "-i", trimmed, "-f", "s16le", "-ac", "1", "-ar", "16000", pcm_f)
      pcm = File.binread(pcm_f)
      dur = pcm.bytesize / 2.0 / 16_000

      # The transcript gate runs for EVERY clip, before acoustics.
      transcript = Edubba::PinyinVoice.transcribe(trimmed)
      if item["kind"] == "line"
        # script-independent: compare base-syllable sequences (the
        # declared pinyin vs the transcript chars' Unihan readings)
        want = item["pinyin"].to_s.split(/[\s,，]+/).reject(&:empty?)
                   .map { |p| Edubba::PinyinVoice.fold_coda(Edubba::PinyinVoice.base_syllable(p)) }
        got = Edubba::PinyinVoice.expand_digits(transcript)
                  .map { |tok| tok =~ /\A\p{Han}\z/ ? Edubba::PinyinVoice.unihan_pinyin.fetch(tok, []).first : tok }
                  .compact
                  .map { |p| Edubba::PinyinVoice.fold_coda(Edubba::PinyinVoice.base_syllable(p)) }
        ratio = Edubba::PinyinVoice.lcs_length(want, got) / want.length.to_f
        if ratio < 0.85
          return [nil, "transcript #{transcript.inspect} does not say the line (#{(ratio * 100).round}% of syllables)"]
        end
      else
        got_han = Edubba::PinyinVoice.han_only(transcript)
        if item["pinyin"].to_s.include?(" ")
          # multi-token demo (the four-tone bar): every spoken char
          # must say the family's base syllable, count must match
          bases = item["pinyin"].split(/\s+/)
          unless got_han.length == bases.length &&
                 got_han.chars.each_with_index.all? { |c, i| Edubba::PinyinVoice.says_base?(c, bases[i]) }
            return [nil, "transcript #{transcript.inspect} is not the declared #{bases.length}-token sequence"]
          end
        else
          unless got_han.length == 1 && transcript == got_han &&
                 Edubba::PinyinVoice.says_base?(got_han, item["pinyin"])
            return [nil, "transcript #{transcript.inspect} does not say #{item['pinyin']} (one syllable)"]
          end
        end
      end

      case item["verify"]
      when "tone"
        track = Edubba::PinyinVoice.clean_track(Edubba::PinyinAudio.pitch_track(pcm))
        expected = Edubba::PinyinAudio.tone_of(item["pinyin"].to_s)
        unless Edubba::PinyinAudio.tone_ok?(expected, track) ||
               (expected == :rise && Edubba::PinyinVoice.late_rise?(track))
          got = Edubba::PinyinAudio.classify(track)
          return [nil, "pitch says #{got}, pinyin #{item['pinyin']} expects #{expected}"]
        end
        # Pedagogical length law (owner ruling 2026-08-15, review of
        # the first full voice: "syllables too short everywhere —
        # may be fluent speech, but no good pedagogy-wise"): a
        # citation clip must be long enough to HEAR the contour.
        span_cfg = plan.dig("engine", "syllable_span") || [0.35, 1.2]
        cut_pass, why = Edubba::PinyinAudio.cut_ok?(pcm, tone: expected,
                                                    span: (span_cfg[0]..span_cfg[1]))
        return [nil, why] unless cut_pass
      when "line"
        return [nil, "duration #{dur.round(2)}s outside 0.8–20s"] unless dur.between?(0.8, 20.0)

        want = Edubba::PinyinVoice.syllable_count(item["pinyin"])
        got = Edubba::PinyinAudio.humps(Edubba::PinyinAudio.envelope(pcm))
        puts "  #{id}: #{dur.round(2)}s, #{got} energy humps for #{want} syllables (report only)"
      else # "loudness" — neutral tone, tone sequences: no contour law
        return [nil, "duration #{dur.round(2)}s implausible"] unless dur.between?(0.1, 20.0)
      end
      [trimmed, nil]
    end

    # Variant groups: all attempts for one base id, in batch order.
    # The FIRST attempt that passes QA ships as the base; later
    # staged siblings are discarded (owner design 2026-08-15: many
    # versions, keep what works). A base fails only when every
    # staged attempt refused.
    batch["items"].group_by { |i| i["base"] || i["id"] }.each do |base, attempts|
      next if ledger["built"].key?(base) && !ARGV.include?("--force") && !force.include?(base)

      winner = nil
      refusals = []
      attempts.each do |item|
        staged = File.join(STAGING, "#{item['id']}.mp3")
        next unless File.exist?(staged)

        if winner
          File.delete(staged)
          next
        end
        wav, why = qa.call(item, staged)
        if wav
          winner = [item, wav]
        else
          refusals << "#{item['id']}: #{why}"
          FileUtils.mv(staged, File.join(rejected, File.basename(staged)))
        end
      end
      if winner.nil?
        failures << "#{base}: #{refusals.join('; ')}" unless refusals.empty?
        next
      end
      item, trimmed = winner
      refusals.each { |r| puts "  (refused attempt) #{r}" }
      out = item["out"]
      FileUtils.mkdir_p(File.dirname(out))
      det = `ffmpeg -i #{trimmed.inspect} -af volumedetect -f null - 2>&1`
      mean = det[/mean_volume: (-?[\d.]+) dB/, 1].to_f
      peak = det[/max_volume: (-?[\d.]+) dB/, 1].to_f
      gain = [-20.0 - mean, -1.0 - peak].min
      system("ffmpeg", "-v", "quiet", "-y", "-i", trimmed, "-ac", "1", "-ar", "44100",
             "-af", format("volume=%.1fdB", gain),
             "-codec:a", "libmp3lame", "-b:a", "64k", out)
      ledger["built"][base] = { "date" => Time.now.strftime("%Y-%m-%d"),
                                "voice_id" => engine_used["voice_id"],
                                "model_id" => engine_used["model_id"],
                                "text" => item["text"], "pinyin" => item["pinyin"] }
      built += 1
      puts "built #{File.basename(out)} (#{item['verify']} ✓#{item['id'] == base ? '' : ", won by #{item['id']}"})"
    end

    unless built.zero?
      File.write(LEDGER, "# GENERATED by bin/pinyin_voice.rb integrate — the record of\n" \
                         "# every synthesized clip: when, which voice, what text.\n" +
                         YAML.dump(ledger))
      Edubba::PinyinVoice.write_credits(ledger)
    end
    puts "voice integrate: #{built} built, #{failures.size} failed"
    failures.each { |f| puts "  FAIL #{f}" }
    puts "Refused clips moved to staging/rejected/; the next synth run regenerates them." unless failures.empty?
    exit(failures.empty? ? 0 : 1)

  when "approve"
    # EAR-APPROVAL (owner override, the final gate): machine
    # referees disagree in the noise regime of half-second clips —
    # the owner listens via the review page and names the winning
    # take; it ships normalized, ledgered with ear_approved: true.
    ids = ARGV.reject { |a| a.start_with?("--") }
    abort "voice approve: name take ids (e.g. da~v0a)" if ids.empty?
    tmp = File.join(STAGING, "_work")
    FileUtils.mkdir_p(tmp)
    ids.each do |take|
      base = take.sub(/~v\d+[a-z]\z/, "")
      src = [File.join(STAGING, "rejected", "#{take}.mp3"),
             File.join(STAGING, "#{take}.mp3")].find { |f| File.exist?(f) }
      abort "voice approve: no staged take #{take}" unless src
      entry = (plan["syllables"] || {})[base] || (plan["lines"] || {})[base]
      abort "voice approve: unknown base #{base}" unless entry

      trimmed = File.join(tmp, "#{take}-appr.wav")
      system("ffmpeg", "-v", "quiet", "-y", "-i", src,
             "-af", "silenceremove=start_periods=1:start_threshold=-40dB:start_silence=0.05," \
                    "areverse,silenceremove=start_periods=1:start_threshold=-30dB:start_silence=0.05,areverse",
             trimmed)
      out = Edubba::PinyinVoice.out_path(base, plan["lines"]&.key?(base) ? "line" : "syllable")
      FileUtils.mkdir_p(File.dirname(out))
      det = `ffmpeg -i #{trimmed.inspect} -af volumedetect -f null - 2>&1`
      mean = det[/mean_volume: (-?[\d.]+) dB/, 1].to_f
      peak = det[/max_volume: (-?[\d.]+) dB/, 1].to_f
      gain = [-20.0 - mean, -1.0 - peak].min
      system("ffmpeg", "-v", "quiet", "-y", "-i", trimmed, "-ac", "1", "-ar", "44100",
             "-af", format("volume=%.1fdB", gain),
             "-codec:a", "libmp3lame", "-b:a", "64k", out)
      ledger["built"][base] = { "date" => Time.now.strftime("%Y-%m-%d"),
                                "voice_id" => plan.dig("engine", "voice_id"),
                                "model_id" => "(per take)",
                                "text" => entry["text"], "pinyin" => entry["pinyin"],
                                "ear_approved" => true, "take" => take }
      puts "approved #{base} (take #{take}) — ear-approved, shipped"
    end
    File.write(LEDGER, "# GENERATED by bin/pinyin_voice.rb integrate — the record of\n" \
                       "# every synthesized clip: when, which voice, what text.\n" + YAML.dump(ledger))
    Edubba::PinyinVoice.write_credits(ledger)

  when "voices"
    key = ENV["ELEVENLABS_API_KEY"].to_s
    abort "voice voices: ELEVENLABS_API_KEY not set — this is the owner-run step" if key.empty?
    uri = URI("#{API_BASE}/v1/voices")
    res = Net::HTTP.start(uri.hostname, uri.port, use_ssl: true) do |h|
      h.request(Net::HTTP::Get.new(uri, "xi-api-key" => key))
    end
    abort "voice voices: HTTP #{res.code} — #{res.body.to_s[0, 300]}" unless res.code == "200"
    JSON.parse(res.body).fetch("voices", []).each do |v|
      puts format("%-24s %s (%s)", v["voice_id"], v["name"], (v["labels"] || {}).values.join(", "))
    end

  else
    abort "pinyin_voice: unknown subcommand #{cmd.inspect}"
  end
end
