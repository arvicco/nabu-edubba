# frozen_string_literal: true

# Authoring-time curriculum instrument (M2-3, concept §3 commitment 1):
# computes frequencies over Nabu corpora and writes committed data
# artifacts. Frequency is one of two sequencing criteria — graphic
# simplicity/iconicity is the other, curated by hand (owner ruling
# 2026-07-29: frequency alone never dictates teaching order).
#
# Two modes:
#   ruby bin/sign_seq.rb                # transliteration-VALUE tables
#   ruby bin/sign_seq.rb signs CORPUS   # true SIGN-occurrence table
#
# Value mode (M2-3): counts spelled values per corpus, never merged
# across corpora (ETCSL c=š j=ŋ vs CDLI sz — mapping between them is
# exactly the kind of silent judgment this project refuses to
# automate).
#
# Sign mode (M5-1, post-P53): corpus lines batched through
# `nabu signs --json` (the frozen P53-2 contract) so occurrences are
# counted per resolved SIGN, not per spelled value. Only honest
# resolutions count — deterministic, qualified, and no-codepoint
# (sign known, unencoded upstream); ambiguous/unknown/broken tokens
# are tallied and excluded, so every count is a floor. Determinatives
# are real signs on the tablet and count as such.

require "date"
require "json"

NABU = ENV.fetch("NABU_BIN", "/Users/vb/Dev/nabu/bin/nabu")
NABU_DIR = File.expand_path("..", File.dirname(NABU))
OUT_DIR = "assets-src/data"
TOP_N = 500
CORPORA = { "etcsl" => "ETCSL (literary Sumerian)",
            "cdli" => "CDLI (documentary, admin-heavy)" }.freeze
BATCH_LINES = 800
BATCH_BYTES = 120_000

module Edubba
  module SignSeq
    module_function

    def count_values(io)
      counts = Hash.new(0)
      passages = 0
      io.each_line do |line|
        passages += 1
        line.scan(/[a-z']+[0-9]*/i) do |value|
          v = value.downcase
          next if v == "x" || v == "n"                # damage / unread markers
          counts[v] += 1
        end
      end
      [counts, passages]
    end

    COUNTED = %w[deterministic qualified no-codepoint].freeze

    # Accumulate one `nabu signs --json` batch into counts (by sign
    # name, glyphs remembered) and a status tally. Returns nothing
    # meaningful; mutates the two accumulators.
    def count_signs_json(json_str, counts, statuses, glyphs = {})
      JSON.parse(json_str)["lines"].each do |line|
        (line["tokens"] || []).each do |t|
          statuses[t["status"]] += 1
          next unless COUNTED.include?(t["status"]) && t["sign_name"]
          counts[t["sign_name"]] += 1
          cps = t["codepoints"] || []
          glyphs[t["sign_name"]] ||= cps.map { |c| c.sub(/\AU\+/, "").hex }.pack("U*") unless cps.empty?
        end
      end
    end
  end
end

def write_table(path, header_lines, rows)
  File.open(path, "w") do |f|
    header_lines.each { |h| f.puts "# #{h}" }
    rows.each { |r| f.puts r.join("\t") }
  end
end

if $PROGRAM_NAME == __FILE__
  abort "sign_seq: #{NABU} not found" unless File.executable?(NABU)
  require "fileutils"
  FileUtils.mkdir_p(OUT_DIR)
  nabu_version = IO.popen([NABU, "version"], err: File::NULL, chdir: NABU_DIR, &:read).strip

  mode = ARGV[0] || "values"

  case mode
  when "values"
    CORPORA.each do |slug, label|
      IO.popen([NABU, "export", "--format=plain", "--lang=sux", "--source=#{slug}"],
               err: File::NULL, chdir: NABU_DIR) do |io|
        counts, passages = Edubba::SignSeq.count_values(io)
        ranked = counts.sort_by { |v, c| [-c, v] }.first(TOP_N)
        write_table(File.join(OUT_DIR, "value-freq-#{slug}.tsv"),
                    ["Sumerian transliteration-value frequency — #{label}",
                     "Generated by bin/sign_seq.rb on #{Date.today} · #{nabu_version}",
                     "Command: nabu export --format=plain --lang=sux --source=#{slug}",
                     "Passages: #{passages} · distinct values: #{counts.size} · top #{TOP_N} kept",
                     "Values are corpus-convention spellings (#{slug == 'etcsl' ? 'c=š, j=ŋ' : 'ATF: sz=š'}); never merged across corpora."],
                    [%w[rank value count]] + ranked.each_with_index.map { |(v, c), i| [i + 1, v, c] })
        puts "sign_seq: #{slug} — #{passages} passages, #{counts.size} values -> value-freq-#{slug}.tsv"
      end
    end
  when "signs"
    slug = ARGV[1]
    abort "sign_seq: signs mode needs a corpus (#{CORPORA.keys.join('|')})" unless CORPORA.key?(slug)
    dialect = slug == "etcsl" ? ["--dialect", "etcsl"] : []
    counts = Hash.new(0)
    statuses = Hash.new(0)
    glyphs = {}
    batch = []
    bytes = 0
    passages = 0
    flush = lambda do
      next if batch.empty?
      json = IO.popen([NABU, "signs", "--json", "--lang=sux", *dialect, batch.join("\n")],
                      err: File::NULL, chdir: NABU_DIR, &:read)
      Edubba::SignSeq.count_signs_json(json, counts, statuses, glyphs)
      batch.clear
      bytes = 0
    end
    IO.popen([NABU, "export", "--format=plain", "--lang=sux", "--source=#{slug}"],
             err: File::NULL, chdir: NABU_DIR) do |io|
      io.each_line do |line|
        line = line.strip
        next if line.empty?
        passages += 1
        batch << line
        bytes += line.bytesize + 1
        flush.call if batch.size >= BATCH_LINES || bytes >= BATCH_BYTES
        warn "sign_seq: #{slug} #{passages} passages..." if (passages % 50_000).zero?
      end
    end
    flush.call
    ranked = counts.sort_by { |s, c| [-c, s] }.first(TOP_N)
    total = statuses.values.sum
    write_table(File.join(OUT_DIR, "sign-freq-#{slug}.tsv"),
                ["Sumerian SIGN-occurrence frequency — #{CORPORA[slug]}",
                 "Generated by bin/sign_seq.rb signs on #{Date.today} · #{nabu_version}",
                 "Pipeline: nabu export --format=plain --lang=sux --source=#{slug} | nabu signs --json (OSL resolution)",
                 "Passages: #{passages} · tokens: #{total} · statuses: #{statuses.sort_by { |_, c| -c }.map { |k, c| "#{k}=#{c}" }.join(' ')}",
                 "Counted statuses: #{Edubba::SignSeq::COUNTED.join(', ')} — ambiguous/unknown/broken excluded; every count is a floor.",
                 "Determinatives count as occurrences of their sign."],
                [%w[rank sign glyph count]] +
                ranked.each_with_index.map { |(s, c), i| [i + 1, s, glyphs[s] || "—", c] })
    puts "sign_seq: #{slug} — #{passages} passages, #{counts.size} signs -> sign-freq-#{slug}.tsv"
  else
    abort "sign_seq: unknown mode #{mode} (values | signs CORPUS)"
  end
end
