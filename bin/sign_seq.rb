# frozen_string_literal: true

# Authoring-time curriculum instrument (M2-3, concept §3 commitment 1):
# computes Sumerian transliteration-VALUE frequencies over Nabu corpora
# and writes committed data artifacts. Frequency is one of two
# sequencing criteria — graphic simplicity/iconicity is the other,
# curated by hand in assets-src/data/sign-teaching.yml (owner ruling
# 2026-07-29: frequency alone never dictates teaching order).
#
# Counts are kept PER CORPUS and never merged: ETCSL and CDLI use
# different transliteration conventions (ETCSL c=š j=ŋ; CDLI sz, g),
# and mapping between them is exactly the kind of silent judgment this
# project refuses to automate. Values are counted, not signs: value →
# sign resolution for the taught set is curated with citations.
#
# Usage: ruby bin/sign_seq.rb   (needs the nabu checkout next door)

require "date"

NABU = ENV.fetch("NABU_BIN", "/Users/vb/Dev/nabu/bin/nabu")
NABU_DIR = File.expand_path("..", File.dirname(NABU))
OUT_DIR = "assets-src/data"
TOP_N = 500
CORPORA = { "etcsl" => "ETCSL (literary Sumerian)",
            "cdli" => "CDLI (documentary, admin-heavy)" }.freeze

abort "sign_seq: #{NABU} not found" unless File.executable?(NABU)

require "fileutils"
FileUtils.mkdir_p(OUT_DIR)

nabu_version = IO.popen([NABU, "version"], err: File::NULL, chdir: NABU_DIR, &:read).strip

def count_values(io)
  counts = Hash.new(0)
  passages = 0
  io.each_line do |line|
    passages += 1
    line.scan(/[a-z']+[0-9]*/i) do |value|
      v = value.downcase
      next if v == "x" || v == "n"                # damage / unread markers
      counts[v] += 1
    end
  end
  [counts, passages]
end

CORPORA.each do |slug, label|
  IO.popen([NABU, "export", "--format=plain", "--lang=sux", "--source=#{slug}"],
           err: File::NULL, chdir: NABU_DIR) do |io|
    counts, passages = count_values(io)
    ranked = counts.sort_by { |v, c| [-c, v] }.first(TOP_N)
    File.open(File.join(OUT_DIR, "value-freq-#{slug}.tsv"), "w") do |f|
      f.puts "# Sumerian transliteration-value frequency — #{label}"
      f.puts "# Generated by bin/sign_seq.rb on #{Date.today} · #{nabu_version}"
      f.puts "# Command: nabu export --format=plain --lang=sux --source=#{slug}"
      f.puts "# Passages: #{passages} · distinct values: #{counts.size} · top #{TOP_N} kept"
      f.puts "# Values are corpus-convention spellings (#{slug == 'etcsl' ? 'c=š, j=ŋ' : 'ATF: sz=š'}); never merged across corpora."
      f.puts "rank\tvalue\tcount"
      ranked.each_with_index { |(v, c), i| f.puts "#{i + 1}\t#{v}\t#{c}" }
    end
    puts "sign_seq: #{slug} — #{passages} passages, #{counts.size} values -> value-freq-#{slug}.tsv"
  end
end
