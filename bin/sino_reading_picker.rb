#!/usr/bin/env ruby
# frozen_string_literal: true

# Sinograph reading picker (M19-4, retro rec 2): coverage-graded
# discovery over the Kanripo slice — parity with the other two
# schools' pickers, ending the hand-hunting that fed S101's first
# fourteen chapters. Streams nabu's jsonl export at clause grain
# (split on 。！？；，、and brackets; (x/y) inline commentary
# stripped), buckets each clause by untaught-character count against
# the cumulative S101 queue inventory (0, 1, or 2 boxes), and ranks
# inside a bucket by DOCUMENT SPREAD — how many distinct Kanripo
# texts carry the exact clause, the corpus's own fame proxy — then
# by length. Boxing is M19-1's, reused, never reimplemented.
#
# Usage: ruby bin/sino_reading_picker.rb [from_ch] [to_ch]
#        output is Markdown; redirect to .docs/s101-stretch4-readings.md

require "yaml"
require "json"
require "set"
require_relative "box_line"

NABU = ENV.fetch("NABU_BIN", "/Users/vb/Dev/nabu/bin/nabu")
NABU_DIR = File.expand_path("..", File.dirname(NABU))
PER_BUCKET = 30
MAX_BOXES = 2

module Edubba
  module SinoReadingPicker
    module_function

    # KR editions carry inline notes as (x/y) parentheticals (both
    # widths); they are commentary, not text — stripped before the
    # clause split.
    COMMENT_RE = /\([^)]*\)|（[^）]*）/
    SPLIT_RE = /[。！？；，、．：《》〈〉「」『』【】\s]+/

    def clauses(text)
      text.gsub(COMMENT_RE, "").split(SPLIT_RE).reject(&:empty?)
    end

    # A candidate clause is pure Han (entity refs, damage marks and
    # stray Latin disqualify) at reading length, with at most
    # max_boxes distinct untaught characters against the full
    # inventory. Returns the untaught list, or nil.
    def qualify(clause, inventory, max_boxes: MAX_BOXES, length: 4..16)
      return nil unless length.cover?(clause.length)
      return nil unless clause.each_char.all? { |c| Edubba::BoxLine.han?(c) }

      wild = clause.each_char.uniq.reject { |c| inventory.include?(c) }
      wild.length <= max_boxes ? wild : nil
    end

    # cumulative: ascending [[chapter, Set]]. The earliest chapter
    # whose inventory leaves at most `allowed` distinct untaught
    # characters in the clause.
    def earliest_chapter(clause, cumulative, allowed)
      ch, = cumulative.find do |_c, inv|
        clause.each_char.uniq.count { |c| Edubba::BoxLine.han?(c) && !inv.include?(c) } <= allowed
      end
      ch
    end

    # Fame first (distinct documents carrying the clause), short
    # before long inside a fame tier.
    def rank(rows)
      rows.sort_by { |r| [-r[:docs], r[:clause].length, r[:clause]] }
    end
  end
end

if $PROGRAM_NAME == __FILE__
  abort "sino_reading_picker: #{NABU} not found" unless File.executable?(NABU)
  from_ch = (ARGV[0] || 0).to_i
  to_ch = (ARGV[1] || 14).to_i

  queue = YAML.safe_load_file("site/_data/sinographs101_queue.yml")["signs"]
  inv = Set.new
  cumulative = []
  queue.select { |s| s["chapter"] }.group_by { |s| s["chapter"] }.sort.each do |ch, rows|
    inv += rows.map { |r| r["char"] }
    cumulative << [ch, inv.dup]
  end
  full = cumulative.last.last

  # clause => {boxes:, docs: Set<int>, urn: first-seen}
  seen = {}
  doc_ids = Hash.new { |h, k| h[k] = h.size }
  passages = 0
  IO.popen([NABU, "export", "--format=jsonl", "--source=kanripo"],
           err: File::NULL, chdir: NABU_DIR) do |io|
    io.each_line do |line|
      rec = JSON.parse(line)
      passages += 1
      doc = doc_ids[rec["urn"].split(":")[3]]
      Edubba::SinoReadingPicker.clauses(rec["text_normalized"].to_s).each do |clause|
        wild = Edubba::SinoReadingPicker.qualify(clause, full)
        next unless wild

        entry = seen[clause] ||= { boxes: wild.length, docs: Set.new, urn: rec["urn"] }
        entry[:docs] << doc
      end
    end
  end
  warn "sino_reading_picker: #{passages} passages streamed, #{seen.size} candidate clauses"

  buckets = Hash.new { |h, k| h[k] = [] }
  seen.each do |clause, e|
    ch = Edubba::SinoReadingPicker.earliest_chapter(clause, cumulative, e[:boxes])
    next unless ch && ch.between?(from_ch, to_ch)

    buckets[[ch, e[:boxes]]] << { clause: clause, docs: e[:docs].size, urn: e[:urn] }
  end

  puts "# S101 reading candidates, chapters #{from_ch}–#{to_ch} (GENERATED by bin/sino_reading_picker.rb)"
  puts "#"
  puts "# Clause-grain sweep of the Kanripo slice; docs = distinct texts"
  puts "# carrying the exact clause (fame proxy). Verify every URN with"
  puts "# nabu search BEFORE writing (rulebook §5); the URN shown is the"
  puts "# first-seen witness, not necessarily the canonical one."
  (from_ch..to_ch).each do |ch|
    (0..MAX_BOXES).each do |n|
      rows = Edubba::SinoReadingPicker.rank(buckets[[ch, n]]).first(PER_BUCKET)
      next if rows.empty?

      puts "\n## ch. #{format('%02d', ch)} · #{n} box#{n == 1 ? '' : 'es'}"
      taught = cumulative.find { |c, _| c >= ch }&.last || full
      rows.each do |r|
        boxed = Edubba::BoxLine.box(r[:clause], taught)
        s = Edubba::BoxLine.share(boxed)
        puts "#{r[:clause]}  |  #{boxed}  |  #{s ? s[:share].round : 0}%  |  " \
             "docs #{r[:docs]}  |  #{r[:urn]}"
      end
    end
  end
end
