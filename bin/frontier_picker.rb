#!/usr/bin/env ruby
# frozen_string_literal: true

# The frontier mode (rulebook cuneiform.md §8, Stage C): lines just
# beyond the current inventory — ≥90% of their distinct signs
# taught, 1–3 signs short — for the per-school "almost yours"
# pages, the one Addenda surface where ▢ appears by design.
#
# Usage: ruby bin/frontier_picker.rb cuneiform|hieroglyphs
#        output Markdown-ish; redirect into .docs/.

require "yaml"
require "json"
require "set"
require_relative "reading_picker"
require_relative "hiero_reading_picker"

NABU = ENV.fetch("NABU_BIN", "/Users/vb/Dev/nabu/bin/nabu")
NABU_DIR = File.expand_path("..", File.dirname(NABU))
CAP = 40

school = ARGV[0] or abort "usage: frontier_picker.rb cuneiform|hieroglyphs"
rows = []

if school == "cuneiform"
  taught = YAML.safe_load_file("site/_data/sign_teaching.yml")["signs"]
  queue = YAML.safe_load_file("site/_data/cuneiform102_queue.yml")["signs"].select { |s| s["chapter"] }
  base = taught.flat_map { |s| Edubba::ReadingPicker.atf_values(s["value"]) }
  inv = { "cdli" => Set.new(base + queue.flat_map { |s| s["value"].split(/\s*[;,]\s*/) }),
          "etcsl" => Set.new(base.map { |v| Edubba::ReadingPicker.fold_etcsl(v) } +
                             queue.map { |s| s["etcsl_value"] || Edubba::ReadingPicker.fold_etcsl(s["value"]) }) }
  %w[cdli etcsl].each do |source|
    IO.popen([NABU, "export", "--format=jsonl", "--lang=sux", "--source=#{source}"],
             err: File::NULL, chdir: NABU_DIR) do |io|
      io.each_line do |line|
        rec = JSON.parse(line)
        tokens = Edubba::ReadingPicker.clean_tokens(rec["text_normalized"].to_s.strip, min: 4, max: 12)
        next unless tokens
        distinct = tokens.uniq
        missing = distinct.reject { |t| inv[source].include?(t) }
        next unless missing.size.between?(1, 3)
        next if (distinct.size - missing.size).fdiv(distinct.size) < 0.9
        glosses = (rec.dig("annotations", "tokens") || []).map { |t| t["label"] }.compact
        rows << [missing.size, "#{source} · #{rec['urn']}  |  #{rec['text']}  |  missing: #{missing.join(' ')}  |  #{glosses.join(' / ')}"]
      end
    end
  end
else
  registry = YAML.safe_load_file("site/_data/hiero_teaching.yml")["signs"]
  queue = YAML.safe_load_file("site/_data/hieroglyphs102_queue.yml")["signs"].select { |s| s["chapter"] }
  inv = Set.new((registry + queue).map { |s| s["gardiner"].upcase })
  IO.popen([NABU, "export", "--format=jsonl", "--lang=egy", "--source=aes"],
           err: File::NULL, chdir: NABU_DIR) do |io|
    io.each_line do |line|
      rec = JSON.parse(line)
      tokens = rec.dig("annotations", "tokens")
      codes = Edubba::HieroReadingPicker.line_codes(tokens, rec["text"])
      next unless codes && codes.size >= 6
      distinct = codes.uniq
      missing = distinct.reject { |c| inv.include?(c) }
      next unless missing.size.between?(1, 3)
      next if (distinct.size - missing.size).fdiv(distinct.size) < 0.9
      glosses = tokens.map { |t| t["gloss"] }.compact
      rows << [missing.size, "aes · #{rec['urn']}  |  #{rec['text']}  |  inv: #{tokens.map { |t| t['hiero_inventar'] }.join(' / ')}  |  missing: #{missing.join(' ')}  |  #{glosses.join(' / ')}"]
    end
  end
end

puts "# Frontier candidates — #{school} (GENERATED by bin/frontier_picker.rb)"
puts "# ≥90% covered, 1–3 distinct signs missing; verify URNs at citation time."
rows.sort_by! { |m, s| [m, -s.length] }
rows.first(CAP).each { |_, s| puts s }
warn "frontier_picker: #{school} — #{rows.size} candidates"