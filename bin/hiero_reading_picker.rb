# frozen_string_literal: true

# Hieroglyph reading picker (M6-1; the P4 ad-hoc sweep promoted to a
# committed instrument, pattern of bin/reading_picker.rb). Streams
# the aes jsonl export and buckets passages by the EARLIEST chapter
# whose cumulative taught Gardiner-code inventory covers every sign
# of every token — so graded readings are found, never composed.
#
# A line qualifies only when it is WHOLE (no damage brackets, no
# lacunae) and every token carries the source's own hiero_inventar
# annotation (the Gardiner codes actually written) — absent
# annotation is absent data, never guessed at.
#
# Inventory comes from the committed registry (hiero_teaching.yml,
# taught_in per chapter) — the same file the validator trusts.
# aes is license class attribution.
#
# Usage: ruby bin/hiero_reading_picker.rb [from_ch] [to_ch]   (default 7 12)
#        output is Markdown; redirect to .docs/p6-readings.md

require "yaml"
require "json"
require "set"

NABU = ENV.fetch("NABU_BIN", "/Users/vb/Dev/nabu/bin/nabu")
NABU_DIR = File.expand_path("..", File.dirname(NABU))
PER_BUCKET = 25
MAX_TOKENS = 12

module Edubba
  module HieroReadingPicker
    module_function

    DAMAGE = /[\[\]⸢⸣⸮…]|\.\.\./

    def damaged?(text) = text.to_s.match?(DAMAGE)

    # "N5;T21" / "M17*G17:N35" -> ["N5", "T21"] / ["M17", "G17", "N35"];
    # mixed-case category names (Aa1, Ff101) upcased so they compare
    # against the registry's AA1-style codes instead of vanishing.
    def codes(inventar) = inventar.to_s.scan(/[A-Za-z]+[0-9]+[A-Za-z]?/).map(&:upcase)

    # All Gardiner codes of a line's tokens, or nil when any token
    # lacks its hiero_inventar annotation (no guessing) or the line
    # is damaged or too long.
    def line_codes(tokens, text)
      return nil if tokens.nil? || tokens.empty? || tokens.size > MAX_TOKENS
      return nil if damaged?(text)
      all = []
      tokens.each do |t|
        return nil if damaged?(t["form"])
        c = codes(t["hiero_inventar"])
        return nil if c.empty?
        all.concat(c)
      end
      all
    end

    # cumulative: ascending [chapter, Set-of-codes]. Earliest cover.
    def readable_chapter(sign_codes, cumulative)
      ch, = cumulative.find { |_c, inv| sign_codes.all? { |g| inv.include?(g) } }
      ch
    end
  end
end

if $PROGRAM_NAME == __FILE__
  abort "hiero_reading_picker: #{NABU} not found" unless File.executable?(NABU)
  course102 = ARGV.delete("--course=102")
  from_ch = (ARGV[0] || (course102 ? 0 : 7)).to_i
  to_ch = (ARGV[1] || (course102 ? 6 : 12)).to_i

  registry = YAML.safe_load_file("site/_data/hiero_teaching.yml")["signs"]
  cumulative = []
  inv = Set.new
  if course102
    # E102: all of E101 is the baseline; buckets follow the queue's
    # chapter pins (site/_data/hieroglyphs102_queue.yml).
    inv += registry.map { |s| s["gardiner"].upcase }
    queue = YAML.safe_load_file("site/_data/hieroglyphs102_queue.yml")["signs"]
    queue.select { |s| s["chapter"] }.group_by { |s| s["chapter"] }.sort.each do |ch, signs|
      inv += signs.map { |s| s["gardiner"].upcase }
      cumulative << [ch, inv.dup]
    end
  else
    registry.select { |s| s["taught_in"] }.group_by { |s| s["taught_in"] }.sort.each do |ch, signs|
      inv += signs.map { |s| s["gardiner"] }
      cumulative << [ch, inv.dup]
    end
  end

  # code -> introducing seat index in the cumulative sequence, for
  # the reinforcement score (rulebook §8/§10, owner ruling
  # 2026-08-04): sweeps rank lines that also revise older signs.
  code_seat = {}
  cumulative.each_with_index do |(_ch, cinv), i|
    cinv.each { |c| code_seat[c] ||= i }
  end
  seat_of_ch = cumulative.each_with_index.to_h { |(ch, _), i| [ch, i] }
  vintages = [1, 2, 4, 8]

  buckets = Hash.new { |h, k| h[k] = [] }
  kept = 0
  IO.popen([NABU, "export", "--format=jsonl", "--lang=egy", "--source=aes"],
           err: File::NULL, chdir: NABU_DIR) do |io|
    io.each_line do |line|
      rec = JSON.parse(line)
      tokens = rec.dig("annotations", "tokens")
      sign_codes = Edubba::HieroReadingPicker.line_codes(tokens, rec["text"])
      next unless sign_codes
      ch = Edubba::HieroReadingPicker.readable_chapter(sign_codes, cumulative)
      next unless ch && ch.between?(from_ch, to_ch)
      glosses = tokens.map { |t| t["gloss"] }.compact
      pos = seat_of_ch[ch]
      hits = sign_codes.uniq.select do |c|
        s = code_seat[c]
        s && vintages.include?(pos - s)
      end
      buckets[ch] << [hits.size,
                      "#{rec['urn']}  |  #{rec['text']}  |  #{tokens.map { |t| t['hiero_inventar'] }.join(' / ')}  |  #{glosses.join(' / ')}  |  reinforces: #{hits.size}#{hits.empty? ? '' : " (#{hits.join(' ')})"}"]
      kept += 1
    end
  end
  buckets.transform_values! { |rows| rows.sort_by { |s, _| -s }.first(PER_BUCKET).map(&:last) }
  warn "hiero_reading_picker: aes — #{kept} candidate lines in chapters #{from_ch}–#{to_ch}"

  puts "# Hieroglyph reading candidates, chapters #{from_ch}–#{to_ch} (GENERATED by bin/hiero_reading_picker.rb)"
  puts "#"
  puts "# Whole aes lines whose every token carries hiero_inventar and"
  puts "# whose every Gardiner code is taught by the bucket's chapter."
  puts "# aes license class: attribution. Verify each URN at citation time."
  (from_ch..to_ch).each do |ch|
    lines = buckets[ch]
    next if lines.empty?
    puts "\n## ch. #{format('%02d', ch)} (license: attribution)"
    lines.each { |l| puts l }
  end
end
