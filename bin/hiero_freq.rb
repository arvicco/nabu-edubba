# frozen_string_literal: true

# aes Gardiner-code frequency table (M6; replaces the P4 ad-hoc
# sweep, which dropped mixed-case categories — Aa1, Ff1 — and so
# undercounted some of the commonest signs in the script). Streams
# the aes jsonl export and counts every code of every token's
# hiero_inventar annotation, upcased; damage does not matter here —
# a sign attested in a broken line is still an attestation.
#
# Usage: ruby bin/hiero_freq.rb   -> assets-src/data/hiero-freq-aes.tsv

require "json"
require "date"

NABU = ENV.fetch("NABU_BIN", "/Users/vb/Dev/nabu/bin/nabu")
NABU_DIR = File.expand_path("..", File.dirname(NABU))
OUT = "assets-src/data/hiero-freq-aes.tsv"

module Edubba
  module HieroFreq
    module_function

    def codes(inventar) = inventar.to_s.scan(/[A-Za-z]+[0-9]+[A-Za-z]?/).map(&:upcase)
  end
end

if $PROGRAM_NAME == __FILE__
  abort "hiero_freq: #{NABU} not found" unless File.executable?(NABU)
  counts = Hash.new(0)
  tokens = 0
  IO.popen([NABU, "export", "--format=jsonl", "--lang=egy", "--source=aes"],
           err: File::NULL, chdir: NABU_DIR) do |io|
    io.each_line do |line|
      (JSON.parse(line).dig("annotations", "tokens") || []).each do |t|
        c = Edubba::HieroFreq.codes(t["hiero_inventar"])
        next if c.empty?
        tokens += 1
        c.each { |g| counts[g] += 1 }
      end
    end
  end
  nabu_version = IO.popen([NABU, "version"], err: File::NULL, chdir: NABU_DIR, &:read).strip
  File.open(OUT, "w") do |f|
    f.puts "# Gardiner-code frequency over the aes corpus hiero_inventar annotations."
    f.puts "# Generated by bin/hiero_freq.rb on #{Date.today} · #{nabu_version}"
    f.puts "# Codes upcased (Aa1 -> AA1); #{tokens} annotated tokens; rank = line order."
    counts.sort_by { |g, c| [-c, g] }.each { |g, c| f.puts "#{g}\t#{c}" }
  end
  puts "hiero_freq: #{counts.size} codes over #{tokens} tokens -> #{OUT}"
end
