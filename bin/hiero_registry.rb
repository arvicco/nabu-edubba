#!/usr/bin/env ruby
# frozen_string_literal: true

# Authoring-time registry generator (M4-2): reads the curated sign
# pool (assets-src/data/hiero-101.yml), resolves each Gardiner code to
# its Unicode codepoint by NAME through the Unicode character database
# (python3 unicodedata — codepoints are verified, never guessed),
# merges aes corpus frequency ranks, and writes the site registry
# site/_data/hiero_teaching.yml (same contract role as
# sign_teaching.yml: additive changes only once published).
#
# Usage: ruby bin/hiero_registry.rb

require "yaml"
require "json"

POOL = "assets-src/data/hiero-101.yml"
FREQ = "assets-src/data/hiero-freq-aes.tsv"
OUT = "site/_data/hiero_teaching.yml"

pool = YAML.safe_load_file(POOL)["signs"]

# Rank Gardiner codes by aes occurrence count (1 = most frequent).
# Keys upcase so the table's mixed-case categories (Aa1) meet the
# pool's AA1-style codes; first (best) rank wins on collision.
ranks = {}
File.readlines(FREQ, chomp: true).reject { |l| l.start_with?("#") || l.empty? }
    .each_with_index { |l, i| ranks[l.split("\t").first.upcase] ||= i + 1 }

# Resolve all codes in one python3 pass; abort on any miss.
codes = pool.map { |s| s["gardiner"] }
py = <<~PY
  import unicodedata, json, re, sys
  out = {}
  for code in json.load(sys.stdin):
      m = re.fullmatch(r"([A-Z]+)(\\d+)([A-Z]?)", code)
      name = f"EGYPTIAN HIEROGLYPH {m.group(1)}{int(m.group(2)):03d}{m.group(3)}"
      try:
          out[code] = ord(unicodedata.lookup(name))
      except KeyError:
          out[code] = None
  json.dump(out, sys.stdout)
PY
resolved = IO.popen(["python3", "-c", py], "r+") do |io|
  io.write(codes.to_json)
  io.close_write
  JSON.parse(io.read)
end
missing = resolved.select { |_, cp| cp.nil? }.keys
abort "hiero_registry: unresolvable Gardiner codes: #{missing.join(', ')}" unless missing.empty?

signs = pool.map do |s|
  cp = resolved[s["gardiner"]]
  {
    "glyph" => [cp].pack("U"),
    "codepoint" => format("%05X", cp),
    "gardiner" => s["gardiner"],
    # name/value/meaning use the sign-linker tip schema so hover
    # bubbles come free: "G17 · m · owl".
    "name" => s["gardiner"],
    "value" => s["translit"],
    "meaning" => s["label"],
    "mdc" => s["mdc"],
    "sound" => s["sound"],
    "taught_in" => s["taught_in"],
    "freq_aes" => ranks[s["gardiner"]],
    "certainty" => s["certainty"]
  }.tap do |h|
    # Sign Codex fields (rulebook §9) — present only where curated.
    h["keyword"] = s["keyword"] if s["keyword"]
    h["confusable_with"] = s["confusable_with"] if s["confusable_with"]
  end
end

# Psych escapes astral-plane glyphs (\U0001313F); the registry must
# carry them literally so the font-coverage scanner sees them.
yaml = { "signs" => signs }.to_yaml.sub(/\A---\n/, "")
              .gsub(/"\\U([0-9A-F]{8})"/) { %("#{[Regexp.last_match(1).hex].pack('U')}") }

File.write(OUT, <<~HEADER + yaml)
  # GENERATED by bin/hiero_registry.rb from assets-src/data/hiero-101.yml
  # + hiero-freq-aes.tsv — do not edit by hand. Hieroglyphs 101 sign
  # registry: codepoints verified against Unicode names; freq_aes is
  # the sign's occurrence rank over the aes corpus hiero annotations.
  # Contract: additive changes only once published (CLAUDE.md rule 5).
HEADER
puts "hiero_registry: #{signs.size} signs -> #{OUT}"
