#!/usr/bin/env ruby
# frozen_string_literal: true

# E102 curriculum compiler (M8-2, rulebook §8): reads the curated
# E102 pool (assets-src/data/hiero-102.yml), resolves each Gardiner
# code to its Unicode codepoint BY NAME (verified, never guessed —
# same discipline as bin/hiero_registry.rb), merges aes frequency
# ranks from the committed table, computes cumulative corpus
# coverage per pinned chapter (E101's 53 signs as the baseline),
# and writes site/_data/hieroglyphs102_queue.yml — additive-only
# once published (CLAUDE.md rule 5; contract test pins the shape).
#
# Coverage = share of all annotated sign-tokens in the aes corpus
# whose Gardiner code is in the cumulative inventory — a floor, and
# fully offline (the committed tsv carries the counts).
#
# Usage: ruby bin/hiero_curriculum.rb

require "yaml"
require "json"
require "set"

POOL101 = "assets-src/data/hiero-101.yml"
POOL102 = "assets-src/data/hiero-102.yml"
FREQ = "assets-src/data/hiero-freq-aes.tsv"
OUT = "site/_data/hieroglyphs102_queue.yml"

pool101 = YAML.safe_load_file(POOL101)["signs"]
pool102 = YAML.safe_load_file(POOL102)["signs"]

counts = {}
total = 0
File.readlines(FREQ, chomp: true).reject { |l| l.start_with?("#") || l.empty? }.each do |l|
  code, n = l.split("\t")
  counts[code.upcase] = counts.fetch(code.upcase, 0) + n.to_i
  total += n.to_i
end
ranks = counts.keys.each_with_index.to_h { |c, i| [c, i + 1] }

codes = pool102.map { |s| s["gardiner"] }
py = <<~PY
  import unicodedata, json, re, sys
  out = {}
  for code in json.load(sys.stdin):
      m = re.fullmatch(r"([A-Z]+)(\\d+)([A-Z]?)", code.upper())
      name = f"EGYPTIAN HIEROGLYPH {m.group(1)}{int(m.group(2)):03d}{m.group(3)}"
      try:
          out[code] = ord(unicodedata.lookup(name))
      except KeyError:
          out[code] = None
  json.dump(out, sys.stdout)
PY
resolved = IO.popen(["python3", "-c", py], "r+") do |io|
  io.write(codes.to_json)
  io.close_write
  JSON.parse(io.read)
end
missing = resolved.select { |_, cp| cp.nil? }.keys
abort "hiero_curriculum: unresolvable Gardiner codes: #{missing.join(', ')}" unless missing.empty?

signs = pool102.map do |s|
  cp = resolved[s["gardiner"]]
  {
    "glyph" => [cp].pack("U"),
    "codepoint" => format("%05X", cp),
    "gardiner" => s["gardiner"],
    "name" => s["gardiner"],
    "value" => s["translit"],
    "meaning" => s["label"],
    "sense" => s["sense"],
    "mdc" => s["mdc"],
    "chapter" => s["chapter"],
    "freq_aes" => ranks[s["gardiner"].upcase],
    "certainty" => s["certainty"]
  }
end

covered = pool101.map { |s| s["gardiner"].upcase }.to_set
cov = ->(inv) { (inv.sum { |c| counts.fetch(c, 0) } * 1000.0 / total).round / 10.0 }
batches = []
baseline = cov.call(covered)
signs.select { |s| s["chapter"] }.group_by { |s| s["chapter"] }.sort.each do |ch, batch|
  covered += batch.map { |s| s["gardiner"].upcase }
  batches << { "chapter" => ch, "signs" => batch.map { |s| s["gardiner"] },
               "coverage_aes_pct" => cov.call(covered) }
end

yaml = { "provenance" => "Generated by bin/hiero_curriculum.rb; coverage = share of " \
                         "annotated aes sign-tokens covered (a floor); E101 baseline #{baseline}%.",
         "signs" => signs, "batches" => batches }.to_yaml.sub(/\A---\n/, "")
                 .gsub(/"\\U([0-9A-F]{8})"/) { %("#{[Regexp.last_match(1).hex].pack('U')}") }

File.write(OUT, <<~HEADER + yaml)
  # GENERATED by bin/hiero_curriculum.rb from assets-src/data/hiero-102.yml
  # + hiero-freq-aes.tsv — do not edit by hand. E102 sign queue:
  # codepoints verified against Unicode names; chapter = the E102
  # chapter that teaches the sign (null = pool candidate).
  # Contract: additive changes only once published (CLAUDE.md rule 5).
HEADER
puts "hiero_curriculum: #{signs.size} signs (#{signs.count { |s| s['chapter'] }} pinned), " \
     "E101 baseline #{baseline}% -> #{OUT}"
