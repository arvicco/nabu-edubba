# frozen_string_literal: true

# Curriculum compiler for C103 Akkadian (M12-3, rulebook §9). The
# stretch-1 pool is fully pinned (built to arrive at Codex Hammurapi
# lines), so unlike bin/curriculum.rb there is no scoring pass — this
# instrument VALIDATES the pins (1–3 NEW signs per chapter, the
# chapter-opening law; veterans uncapped) and reports cumulative
# coverage of the OB value table, then emits the queue.
#
# Coverage counts, per chapter: the queue's own values so far PLUS
# the ambient veteran base — primary ATF values of every sux-taught
# sign that double unchanged as OB syllables (computed as the
# intersection with the akkob table, not curated by hand). A floor,
# as always.
#
# Usage: ruby bin/akk_curriculum.rb  -> writes site/_data/cuneiform103_queue.yml

require "yaml"
require "date"
require_relative "curriculum"

module Edubba
  module AkkCurriculum
    FREQ_TSV = "assets-src/data/value-freq-akkob.tsv"

    module_function

    def table_values(freq_tsv = FREQ_TSV)
      File.readlines(freq_tsv, chomp: true)
          .reject { |l| l.start_with?("#", "rank\t") }
          .map { |l| l.split("\t")[1] }
    end

    def ambient(taught_values, freq_tsv = FREQ_TSV)
      taught_values & table_values(freq_tsv)
    end

    def validate!(pool)
      pool.group_by { |s| s["chapter"] }.each do |ch, signs|
        abort "akk_curriculum: unpinned sign #{signs.map { |s| s['name'] }.join(',')}" if ch.nil?
        fresh = signs.count { |s| !s["veteran"] }
        next if fresh.between?(1, 3)

        abort "akk_curriculum: ch #{ch} pins #{fresh} NEW signs — the law says 1-3"
      end
      dup = pool.map { |s| s["name"] }.tally.select { |_, n| n > 1 }
      abort "akk_curriculum: duplicate rows #{dup.keys.join(',')}" unless dup.empty?
    end
  end
end

if $PROGRAM_NAME == __FILE__
  pool = YAML.safe_load_file("assets-src/data/pool-103.yml")["signs"]
  Edubba::AkkCurriculum.validate!(pool)

  taught = YAML.safe_load_file("site/_data/sign_teaching.yml")["signs"] +
           YAML.safe_load_file("site/_data/cuneiform102_queue.yml")["signs"].select { |s| s["chapter"] }
  base = Edubba::AkkCurriculum.ambient(
    taught.map { |s| Edubba::Curriculum.atf_value(s["value"]) }.compact
  )

  cum = []
  report = pool.group_by { |s| s["chapter"] }.sort.map do |ch, signs|
    cum += signs.map { |s| s["value"] }
    { "chapter" => ch,
      "signs" => signs.map { |s| s["veteran"] ? "#{s['name']} (vet)" : s["name"] },
      "coverage_akkob_pct" => Edubba::Curriculum.coverage(
        Edubba::AkkCurriculum::FREQ_TSV, base + cum
      ).round(1) }
  end

  out = {
    "provenance" => "Generated by bin/akk_curriculum.rb on #{Date.today}; " \
                    "all batches pinned (stretch-1 contract); coverage = queue values " \
                    "+ ambient veteran base (#{base.size} sux values doubling as OB syllables); a floor.",
    "batches" => report,
    "signs" => pool
  }
  File.write("site/_data/cuneiform103_queue.yml",
             "# GENERATED by bin/akk_curriculum.rb — do not edit by hand.\n" + YAML.dump(out))
  report.each { |b| puts "ch. #{b['chapter']}: #{b['signs'].join(', ')} — OB coverage #{b['coverage_akkob_pct']}%" }
end
