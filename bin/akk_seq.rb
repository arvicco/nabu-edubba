# frozen_string_literal: true

# Authoring-time curriculum instrument (M12-2, rulebook cuneiform.md
# §9): value frequencies for AKKADIAN over the Old Babylonian
# sub-corpus — the separate frequency base the language-separation
# law demands (sux and akk ranks never mix).
#
#   ruby bin/akk_seq.rb        # writes assets-src/data/value-freq-akkob.tsv
#                              #    and assets-src/data/sumerogram-freq-akkob.tsv
#
# The OB slice: `nabu lect list` names every document ruled akk:ob
# (the ratified facet→lect rules); we keep CDLI lines whose document
# is in that set. Counting follows the sign_seq.rb family — raw ATF
# corpus-convention spellings, never folded or merged — but Akkadian
# ATF needs three tallies the Sumerian counter didn't: syllabic
# values (the syllabary curriculum's base), Sumerograms (`_..._`
# stretches), and determinatives (`{d}`, `{ki}` …). Restored text in
# [brackets] counts (the anchor text is a composite); damage x and
# number notation do not. Names spelled syllabically inside
# determinative words count as syllables — a floor, stated here.

require "date"

NABU = ENV.fetch("NABU_BIN", "/Users/vb/Dev/nabu/bin/nabu")
NABU_DIR = File.expand_path("..", File.dirname(NABU))
OUT_DIR = "assets-src/data"
TOP_N = 500

module Edubba
  module AkkSeq
    VALUE = /\A(?:[a-z']|[st],)+[0-9]*\z/
    module_function

    # One ATF line into the three tallies. Underscore pairs delimit
    # Sumerogram stretches (split gives alternating outside/inside
    # segments); braces mark determinatives.
    def count_line(line, values, sumerograms, determinatives)
      clean = line.gsub(/[\[\]#!?<>]/, "")
      clean.split("_", -1).each_with_index do |segment, i|
        if i.odd?
          segment.split.each do |word|
            next if word.match?(/\A[0-9\/]+\(.*\z/)

            sumerograms[word] += 1 if word.match?(/[a-z]/)
          end
        else
          segment.scan(/\{([a-z0-9]+)\}/) { determinatives["{#{$1}}"] += 1 }
          segment.gsub(/\{[a-z0-9]+\}/, " ").split.each do |word|
            next if word.match?(/\A[0-9\/]+\(/) || word.match?(/\A[0-9]/)

            word.split("-").each do |v|
              v = v.downcase
              next if v == "x" || v == "n" || !v.match?(VALUE)

              values[v] += 1
            end
          end
        end
      end
    end

    def ob_documents(io)
      set = {}
      io.each_line do |line|
        urn, code, lect = line.strip.split("\t")
        set[urn] = true if code == "akk" && lect == "akk:ob" && urn&.start_with?("urn:nabu:cdli:")
      end
      set
    end

    def doc_urn(passage_urn)
      passage_urn.split(":").first(4).join(":")
    end
  end
end

def write_table(path, header_lines, rows)
  File.open(path, "w") do |f|
    header_lines.each { |h| f.puts "# #{h}" }
    rows.each { |r| f.puts r.join("\t") }
  end
end

if $PROGRAM_NAME == __FILE__
  require "json"
  require "fileutils"
  abort "akk_seq: #{NABU} not found" unless File.executable?(NABU)
  FileUtils.mkdir_p(OUT_DIR)
  nabu_version = IO.popen([NABU, "version"], err: File::NULL, chdir: NABU_DIR, &:read).strip

  ob = IO.popen([NABU, "lect", "list", "--format=tsv", "--limit=0"],
                err: File::NULL, chdir: NABU_DIR) { |io| Edubba::AkkSeq.ob_documents(io) }
  abort "akk_seq: no akk:ob documents from nabu lect list" if ob.empty?

  values = Hash.new(0)
  sumerograms = Hash.new(0)
  determinatives = Hash.new(0)
  passages = 0
  IO.popen([NABU, "export", "--format=jsonl", "--lang=akk", "--source=cdli"],
           err: File::NULL, chdir: NABU_DIR) do |io|
    io.each_line do |line|
      rec = JSON.parse(line)
      next unless ob[Edubba::AkkSeq.doc_urn(rec["urn"])]

      passages += 1
      Edubba::AkkSeq.count_line(rec["text"].to_s, values, sumerograms, determinatives)
      warn "akk_seq: #{passages} OB passages..." if (passages % 50_000).zero?
    end
  end

  common = ["Generated by bin/akk_seq.rb on #{Date.today} · #{nabu_version}",
            "OB slice: nabu lect list (akk:ob rulings, #{ob.size} CDLI documents) ∩ nabu export --lang=akk --source=cdli",
            "Passages: #{passages} · raw ATF spellings, never folded (sz/s,/t,); a separate base — never mixed with sux ranks (§9)."]
  ranked_v = values.sort_by { |v, c| [-c, v] }.first(TOP_N)
  write_table(File.join(OUT_DIR, "value-freq-akkob.tsv"),
              ["Akkadian syllabic-value frequency — CDLI, Old Babylonian slice"] + common +
              ["Syllabic values only: Sumerograms and determinatives tallied separately (sumerogram-freq-akkob.tsv)."],
              [%w[rank value count]] + ranked_v.each_with_index.map { |(v, c), i| [i + 1, v, c] })
  ranked_s = (sumerograms.map { |w, c| [w.upcase, c] }.to_h.merge(determinatives.to_h))
             .sort_by { |v, c| [-c, v] }.first(TOP_N)
  write_table(File.join(OUT_DIR, "sumerogram-freq-akkob.tsv"),
              ["Sumerogram + determinative frequency in OB Akkadian — CDLI, Old Babylonian slice"] + common +
              ["Sumerograms upcased for display ({d} rows are determinatives); ATF dots kept (KU3.BABBAR)."],
              [%w[rank form count]] + ranked_s.each_with_index.map { |(v, c), i| [i + 1, v, c] })
  puts "akk_seq: #{passages} OB passages — #{values.size} values, #{sumerograms.size} sumerograms -> #{OUT_DIR}"
end
