# frozen_string_literal: true

# Curriculum compiler v1 (M3-2). Orders a curated candidate pool by
# the two ratified criteria — corpus frequency AND graphic simplicity
# (concept §3.1) — chunks it into per-chapter batches, and reports
# cumulative corpus coverage so the curriculum's progress is a
# measured fact, not a feeling.
#
# score = best_rank + WEDGE_WEIGHT * wedges   (lower = earlier)
#   best_rank    = min(freq_etcsl, freq_cdli) (999 if unranked)
#   WEDGE_WEIGHT = 8 — one wedge of complexity "costs" eight ranks of
#                  frequency; chosen so ME (2 wedges, rank 17) lands
#                  ahead of RA (8 wedges, rank 7), which matches the
#                  owner's ruling that simplicity pulls simple signs
#                  earlier even against raw frequency.
#
# Coverage: share of all value-occurrences in each corpus covered by
# the cumulative taught inventory (101 signs + queue so far), using
# each sign's PRIMARY value only — a floor, not a ceiling (polyvalent
# signs cover more than we count).
#
# Usage: ruby bin/curriculum.rb   -> writes site/_data/cuneiform102_queue.yml

require "yaml"
require "date"

WEDGE_WEIGHT = 8
BATCHES = { 0 => 3, 1 => 3, 2 => 3, 3 => 3, 4 => 3, 5 => 3 }.freeze

module Edubba
  module Curriculum
    module_function

    def wedge_num(w) = w.to_s.delete("~").to_i

    def score(sign)
      best = [sign["freq_etcsl"] || 999, sign["freq_cdli"] || 999].min
      best + WEDGE_WEIGHT * wedge_num(sign["wedges"])
    end

    def order(pool)
      pool.sort_by { |s| [score(s), s["name"]] }
    end

    def assign_batches(ordered, batches = BATCHES)
      out = []
      queue = ordered.dup
      batches.each do |chapter, n|
        queue.shift(n).each { |s| out << s.merge("chapter" => chapter, "score" => score(s)) }
      end
      out + queue.map { |s| s.merge("chapter" => nil, "score" => score(s)) }
    end

    def coverage(freq_tsv, covered_values)
      total = hit = 0
      File.readlines(freq_tsv, chomp: true).each do |line|
        next if line.start_with?("#") || line.start_with?("rank\t")
        _rank, value, count = line.split("\t")
        total += count.to_i
        hit += count.to_i if covered_values.include?(value)
      end
      total.zero? ? 0.0 : (100.0 * hit / total)
    end
  end
end

if $PROGRAM_NAME == __FILE__
  pool = YAML.safe_load_file("assets-src/data/pool-102.yml")["signs"]
  taught = YAML.safe_load_file("site/_data/sign_teaching.yml")["signs"]

  queued = Edubba::Curriculum.assign_batches(Edubba::Curriculum.order(pool))

  # primary ATF/etcsl values of the already-taught 101 inventory
  atf_taught = taught.map { |s| s["value"][/[a-zŋšḫ']+[0-9]*/] }.compact
  etcsl_map = { "sze" => "ce", "sze3" => "ce3", "szul" => "cul" }

  cdli_vals = atf_taught.dup
  etcsl_vals = atf_taught.map { |v| etcsl_map[v] || v }
  cum = []
  report = queued.select { |s| s["chapter"] }.group_by { |s| s["chapter"] }.sort.map do |ch, signs|
    cum += signs
    cdli_now = cdli_vals + cum.map { |s| s["value"] }
    etcsl_now = etcsl_vals + cum.map { |s| s["etcsl_value"] || s["value"] }
    {
      "chapter" => ch,
      "signs" => signs.map { |s| s["name"] },
      "coverage_etcsl_pct" => Edubba::Curriculum.coverage("assets-src/data/value-freq-etcsl.tsv", etcsl_now).round(1),
      "coverage_cdli_pct" => Edubba::Curriculum.coverage("assets-src/data/value-freq-cdli.tsv", cdli_now).round(1)
    }
  end

  out = {
    "provenance" => "Generated by bin/curriculum.rb on #{Date.today}; " \
                    "score = best_rank + #{WEDGE_WEIGHT} x wedges; " \
                    "coverage counts primary values only (a floor).",
    "batches" => report,
    "signs" => queued
  }
  File.write("site/_data/cuneiform102_queue.yml",
             "# GENERATED by bin/curriculum.rb — do not edit by hand.\n" + YAML.dump(out))
  report.each { |b| puts "ch. #{b['chapter']}: #{b['signs'].join(', ')} — coverage etcsl #{b['coverage_etcsl_pct']}% / cdli #{b['coverage_cdli_pct']}%" }
end
