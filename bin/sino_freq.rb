# frozen_string_literal: true

# Kanripo character-frequency table (M15-3, rulebook §5). Streams the
# kanripo jsonl export (waves 1–3: classics, histories, masters,
# belles-lettres, Daoist canon — 4.57M lzh passages, CC BY-SA 4.0)
# and counts every Han character; doc spread (in how many of the
# 5,122 texts a character appears) is carried beside the raw count so
# one giant text cannot masquerade as the whole tradition. The top of
# the table is annotated from the Unihan release files and the
# BabelStone IDS database read from the Nabu checkout next door:
# stroke count and Mandarin reading feed the simplicity axis
# (concept §3.1), the IDS decomposition feeds component teaching.
#
# Usage: ruby bin/sino_freq.rb   -> assets-src/data/char-freq-kanripo.tsv

require "json"
require "date"

NABU = ENV.fetch("NABU_BIN", "/Users/vb/Dev/nabu/bin/nabu")
NABU_DIR = File.expand_path("..", File.dirname(NABU))
UNIHAN_DIR = ENV.fetch("UNIHAN_DIR", File.join(NABU_DIR, "canonical/unihan"))
IDS_TXT = ENV.fetch("IDS_TXT", File.join(NABU_DIR, "canonical/babelstone-ids/IDS.TXT"))
OUT = "assets-src/data/char-freq-kanripo.tsv"
TOP = 3000

module Edubba
  module SinoFreq
    module_function

    # Every Han character of a passage, in order (punctuation, kana,
    # hexagram symbols and the like fall away).
    def han_chars(text) = text.to_s.scan(/\p{Han}/)

    # urn:nabu:kanripo:KR1a0001:001:1a -> urn:nabu:kanripo:KR1a0001
    def doc_of(urn) = urn.to_s.split(":").first(4).join(":")

    # One Unihan release file -> { char => value } for one field tag.
    def unihan_field(lines, tag)
      lines.each_with_object({}) do |line, map|
        cp, field, value = line.chomp.split("\t", 3)
        next unless field == tag && cp&.start_with?("U+")

        map[[cp[2..].hex].pack("U")] = value
      end
    end

    # BabelStone IDS.TXT (UTF-8 BOM, CRLF; sequences shaped
    # ^IDS$(sources), alternatives whitespace-separated) ->
    # { char => bare IDS of the first sequence }.
    def ids_map(lines)
      lines.each_with_object({}) do |raw, map|
        line = raw.sub(/\A\u{FEFF}/, "").chomp
        next if line.empty? || line.start_with?("#")

        _cp, char, rest = line.split("\t", 3)
        next unless char && rest

        seq = rest.split(/\s+/).first.to_s
        map[char] = seq.sub(/\A\^/, "").sub(/\$.*\z/, "")
      end
    end
  end
end

if $PROGRAM_NAME == __FILE__
  abort "sino_freq: #{NABU} not found" unless File.exist?(NABU)
  counts = Hash.new(0)
  doc_counts = Hash.new(0)
  last_doc = {}
  tokens = 0
  passages = 0
  IO.popen(["bundle", "exec", "bin/nabu", "export", "--format=jsonl",
            "--lang=lzh", "--source=kanripo"],
           err: File::NULL, chdir: NABU_DIR) do |io|
    io.each_line do |line|
      row = JSON.parse(line)
      doc = Edubba::SinoFreq.doc_of(row["urn"])
      passages += 1
      Edubba::SinoFreq.han_chars(row["text"]).each do |c|
        tokens += 1
        counts[c] += 1
        if last_doc[c] != doc
          last_doc[c] = doc
          doc_counts[c] += 1
        end
      end
    end
  end
  abort "sino_freq: empty export — is kanripo synced?" if counts.empty?

  strokes = Edubba::SinoFreq.unihan_field(
    File.foreach(File.join(UNIHAN_DIR, "Unihan_IRGSources.txt")), "kTotalStrokes"
  )
  pinyin = Edubba::SinoFreq.unihan_field(
    File.foreach(File.join(UNIHAN_DIR, "Unihan_Readings.txt")), "kMandarin"
  )
  ids = Edubba::SinoFreq.ids_map(File.foreach(IDS_TXT))

  nabu_version = IO.popen(["bundle", "exec", "bin/nabu", "version"],
                          err: File::NULL, chdir: NABU_DIR, &:read).strip
  ranked = counts.sort_by { |c, n| [-n, c] }
  File.open(OUT, "w") do |f|
    f.puts "# Han-character frequency over the Kanripo corpus (Kanseki Repository, CC BY-SA 4.0)."
    f.puts "# Generated by bin/sino_freq.rb on #{Date.today} · #{nabu_version}"
    f.puts "# #{tokens} character tokens · #{counts.size} distinct characters · " \
           "#{passages} passages · docs = texts containing the character."
    f.puts "# Top #{TOP} rows carry Unihan kTotalStrokes/kMandarin and BabelStone IDS."
    f.puts "rank\tchar\tcount\tdocs\tstrokes\tpinyin\tids"
    ranked.first(TOP).each_with_index do |(c, n), i|
      f.puts [i + 1, c, n, doc_counts[c],
              strokes[c], pinyin[c], ids[c]].join("\t")
    end
  end
  puts "sino_freq: #{counts.size} chars over #{tokens} tokens -> #{OUT} (top #{TOP})"
end
