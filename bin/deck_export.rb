#!/usr/bin/env ruby
# frozen_string_literal: true

# Study-deck exporter (rulebook cuneiform.md §8, Stage C): emits one
# Anki-importable TSV per course into site/assets/decks/. One card
# per sign — front the glyph, back keyword · name · readings ·
# meaning · the codex page's memory hook, plus the codex's attested
# line WHEN its license class is attribution (CDLI, aes). ETCSL's
# non-commercial terms keep its lines out of redistributable decks:
# the exporter includes attribution lines, skips non-commercial
# ones, and HARD-FAILS on any license it does not recognize rather
# than filtering silently.
#
# Usage: ruby bin/deck_export.rb   (from the repo root)

require "yaml"
require_relative "../script/rulebook"
require_relative "../script/warmup"

OUT_DIR = "site/assets/decks"

# deck => [school, registry, seat key, codex shelf dir]. The 103
# deck reads the AKKADIAN shelf (§9 separation) — its hooks and
# attested lines come from addenda-akk, never the Sumerian codex.
COURSES = {
  "edubba-cuneiform-101" => ["cuneiform", "site/_data/sign_teaching.yml", :taught_in, "addenda"],
  "edubba-cuneiform-102" => ["cuneiform", "site/_data/cuneiform102_queue.yml", :chapter, "addenda"],
  "edubba-cuneiform-103" => ["cuneiform", "site/_data/cuneiform103_queue.yml", :chapter, "addenda-akk"],
  "edubba-hieroglyphs-101" => ["hieroglyphs", "site/_data/hiero_teaching.yml", :taught_in, "addenda"],
  "edubba-hieroglyphs-102" => ["hieroglyphs", "site/_data/hieroglyphs102_queue.yml", :chapter, "addenda"]
}.freeze

def strip_prose(text)
  text.gsub(/\[([^\]]*)\]\((?:[^)]*)\)/, '\1')   # md links -> text
      .gsub(/<[^>]+>/, "")                        # html tags
      .gsub(/\*\*([^*]*)\*\*/, '\1').gsub(/\*([^*]*)\*/, '\1')
      .gsub(/\s+/, " ").strip
end

def codex_bits(school, ident, shelf = "addenda")
  path = "site/#{school}/#{shelf}/signs/#{Edubba::Rulebook.sign_slug(ident)}.md"
  text = File.read(path, encoding: "UTF-8")

  hook = text[/^## How to remember it\n\n(.+?)\n\n## /m, 1]
  hook = strip_prose(hook.to_s)

  line = nil
  if (m = text.match(%r{<span class="translit(?: atf)?">([^<]+)</span><span class="gloss">([^<]+)</span>}))
    caption = text[%r{<figcaption class="citation">(.+?)</figcaption>}m, 1].to_s
    urn = caption[/urn:nabu:[a-z0-9:.'\-]+/i]
    license = caption[/license:\s*([^.<]+)/, 1].to_s.gsub(/\s+/, " ").strip
    case license
    when /\Aattribution\z/
      line = { translit: m[1], gloss: strip_prose(m[2]), urn: urn }
    when /ETCSL · non-commercial/
      line = nil   # lawful skip: not redistributable
    else
      abort "deck_export: #{path}: unrecognized license #{license.inspect} — refusing to guess"
    end
  end
  [hook, line]
end

require "fileutils"
FileUtils.mkdir_p(OUT_DIR)

COURSES.each do |deck, (school, registry, seat_key, shelf)|
  signs = YAML.safe_load_file(registry)["signs"]
             .select { |s| s[seat_key.to_s] }
  rows = signs.map do |s|
    ident = s["gardiner"] || s["name"]
    hook, line = codex_bits(school, ident, shelf)
    reads = Edubba::Warmup.reads(s, school)
    back = +"<b>#{s['keyword']}</b> · #{ident} · <i>#{reads}</i> · #{s['meaning']}"
    back << "<br>#{hook}" unless hook.empty?
    back << "<br><i>#{line[:translit]}</i> — #{line[:gloss]} (#{line[:urn]}, license: attribution)" if line
    back << "<br>Edubba · edubba.ac · CC BY-SA 4.0; quoted lines carry their own licenses"
    "#{s['glyph']}\t#{back}\tedubba #{deck}"
  end
  File.write("#{OUT_DIR}/#{deck}.txt", <<~HEAD + rows.join("\n") + "\n")
    #separator:tab
    #html:true
    # #{deck} — one card per sign taught in the course, generated by
    # bin/deck_export.rb from the Edubba registries and Sign Codex.
    # Import into Anki (File > Import), then enable FSRS in the deck
    # options for evidence-backed scheduling.
  HEAD
  puts "#{deck}: #{rows.size} cards"
end
